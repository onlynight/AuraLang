#![cfg(feature = "llvm")]

//! Fix 6 — C ABI 蹦床可变参数（4→8）测试
//!
//! 验证蹦床函数支持最多 8 个参数。

use compiler::vm::ffi::trampoline_ptr;

// ─────────────────────────────────────────────────────────────────────────────
// 1. 蹦床函数指针非空
// ─────────────────────────────────────────────────────────────────────────────

#[test]
fn test_trampoline_ptr_nonzero() {
    let ptr = trampoline_ptr();
    assert_ne!(ptr, 0, "蹦床函数指针不应为 0");
}

// ─────────────────────────────────────────────────────────────────────────────
// 2. 蹦床函数签名验证（编译期检查）
// ─────────────────────────────────────────────────────────────────────────────

#[test]
fn test_trampoline_signature() {
    // 验证蹦床函数可以以 8 参数形式调用
    // 此测试仅验证编译通过，运行时测试需通过 C 代码触发
    let ptr = trampoline_ptr();
    // 转换为 8 参数函数指针类型
    let _func_type = unsafe {
        std::mem::transmute::<
            i64,
            unsafe extern "C" fn(
                *mut std::ffi::c_void,
                i64,
                i64,
                i64,
                i64,
                i64,
                i64,
                i64,
                i64,
            ) -> i64,
        >(ptr)
    };
    // 仅验证类型转换可行，不实际调用
}

// ─────────────────────────────────────────────────────────────────────────────
// 3. 蹦床参数上限常量
// ─────────────────────────────────────────────────────────────────────────────

const TRAMPOLINE_MAX_ARGS: usize = 8;

#[test]
fn test_trampoline_max_args() {
    assert_eq!(TRAMPOLINE_MAX_ARGS, 8, "蹦床应支持最多 8 个参数");
}
